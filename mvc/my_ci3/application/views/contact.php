<script>
const form = document.getElementById("contactForm");
const submitButton = document.getElementById("submitButton");
const buttonText = document.getElementById("buttonText");
const loadingSpan = document.getElementById("loadingSpan");
const nameInput = document.getElementById("name");
const emailInput = document.getElementById("email");
const subjectInput = document.getElementById("subject");
const messageInput = document.getElementById("message");
const charCount = document.getElementById("charCount");
const successOverlay = document.getElementById("successOverlay");
const closeSuccess = document.getElementById("closeSuccess");
const copyEmail = document.getElementById("copyEmail");

messageInput.addEventListener("input", () => {
  charCount.textContent = `${messageInput.value.length} / 1000`;
});

function setError(input, hasError) {
  const errMsg = input.parentElement.querySelector(".error-message");
  if (hasError) {
    input.classList.add("border-[#ff6496]", "shadow-[0_0_0_3px_rgba(255,100,150,0.06)]");
    errMsg.classList.remove("hidden");
  } else {
    input.classList.remove("border-[#ff6496]", "shadow-[0_0_0_3px_rgba(255,100,150,0.06)]");
    errMsg.classList.add("hidden");
  }
}

function isValidEmail(email) {
  return /^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email);
}

function validateForm() {
  let valid = true;
  if (nameInput.value.trim() === "") { setError(nameInput, true); valid = false; } else setError(nameInput, false);
  if (!isValidEmail(emailInput.value.trim())) { setError(emailInput, true); valid = false; } else setError(emailInput, false);
  if (subjectInput.value.trim() === "") { setError(subjectInput, true); valid = false; } else setError(subjectInput, false);
  if (messageInput.value.trim() === "") { setError(messageInput, true); valid = false; } else setError(messageInput, false);
  return valid;
}

[nameInput, emailInput, subjectInput, messageInput].forEach(input => {
  input.addEventListener("input", () => setError(input, false));
});

form.addEventListener("submit", function (event) {
  event.preventDefault();
  if (!validateForm()) return;

  buttonText.classList.add("hidden");
  loadingSpan.classList.remove("hidden");
  loadingSpan.classList.add("inline-flex");


  setTimeout(() => {
    buttonText.classList.remove("hidden");
    loadingSpan.classList.add("hidden");
    loadingSpan.classList.remove("inline-flex");
    successOverlay.classList.add("show");
    form.reset();
    charCount.textContent = "0 / 1000";
  }, 1400);
});

closeSuccess.addEventListener("click", () => successOverlay.classList.remove("show"));
successOverlay.addEventListener("click", (event) => {
  if (event.target === successOverlay) successOverlay.classList.remove("show");
});

copyEmail.addEventListener("click", async () => {
  try {
    await navigator.clipboard.writeText("arezoroshani11@gmail.com");
    copyEmail.textContent = "✓ Email copied!";
    setTimeout(() => { copyEmail.textContent = "📋 Copy email"; }, 1800);
  } catch {
    copyEmail.textContent = "Copy failed";
  }
});

document.addEventListener("click", (event) => {
  if (event.target.closest("button") || event.target.closest("input") || event.target.closest("textarea")) return;
  const sparkle = document.createElement("span");
  sparkle.textContent = "✦";
  sparkle.className = "fixed pointer-events-none z-[999] text-[18px] text-[#ffc4e8] animate-sparkle-click";
  sparkle.style.left = event.clientX + "px";
  sparkle.style.top = event.clientY + "px";
  document.body.appendChild(sparkle);
  setTimeout(() => sparkle.remove(), 800);
});
</script>

